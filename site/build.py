"""Build the static demo site data from the same sample files and rules the CLI uses.

    python3 site/build.py        # writes site/data.js

No network, no keys. The page itself is plain HTML, CSS and JS with no build step.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "ai-tool-ops-desk"))
import opsdesk  # noqa: E402


def render() -> str:
    data = opsdesk.site_data()
    return "// Generated by site/build.py from ai-tool-ops-desk/data. Sample data only.\n" \
           "window.OPSDESK_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"


def main() -> int:
    (HERE / "data.js").write_text(render())
    print(f"Wrote {HERE / 'data.js'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
